WHY_DRESSINGS_MATTER = """A dressing covers the wound like a shield, keeping out dirt and germs and protecting new tissue from knocks. Research since the 1960s has shown that wounds kept moist heal faster than wounds left open to dry into a scab, because new skin cells can slide across a moist surface instead of digging under a hard crust. A good dressing also soaks up extra fluid so the skin around the wound doesn't get soggy. By keeping germs out, it lowers the chance of infection."""

WOUND_HEALING_STAGES = [
    (
        "Hemostasis (stopping the bleeding)",
        "Right after an injury, blood vessels tighten to slow the bleeding. Tiny blood cells called platelets stick together and plug the damaged spot, and a clot forms. This starts within seconds and is mostly done within minutes to hours.",
    ),
    (
        "Inflammation (the body's response to injury)",
        "Blood vessels widen so that immune cells can reach the area. These cells clean away germs and dead tissue, which is why the wound can look red, warm, and swollen. This usually lasts about 1 to 4 days.",
    ),
    (
        "Proliferation (new tissue forms)",
        "The body builds new tissue to fill the gap, including fresh blood vessels and a collagen framework. New skin then grows over the top and the wound edges pull closer together. This phase runs from roughly day 4 to week 3.",
    ),
    (
        "Remodeling (the repaired tissue strengthens)",
        "The new tissue is slowly reorganized and made stronger, and the scar becomes flatter and paler. This stage starts around week 3 and can last up to a year, and some sources say it can take up to two years.",
    ),
]

BURN_DEGREES = [
    (
        "1st-degree burn",
        "Only the top layer of skin is hurt. It looks pink to red and dry, with no blisters, and it is moderately painful. It usually heals in about 5 to 10 days without scarring. A mild sunburn is a typical example.",
    ),
    (
        "2nd-degree burn",
        "The burn goes deeper, past the top layer into the layer beneath. The skin looks red, swollen, and wet, and blisters are common. It hurts more than a 1st-degree burn and takes longer to heal. Deeper ones can take weeks and may leave a scar.",
    ),
    (
        "Other or uncertain degree: see a doctor",
        """It can be hard to tell how deep a burn is, and it can look worse after a day or two. Get medical help if:
- The burn is large or deep, bigger than the person's hand.
- The skin looks white, waxy, leathery, or charred, or the burn is strangely painless. This can mean a very deep burn.
- It is on the face, hands, feet, arms, legs, or genitals.
- It was caused by chemicals or electricity.
- The injured person is a young child, or has a serious health condition.
- There are signs of infection: the wound becomes more painful or smelly, there is a fever of 38°C or higher, the dressing soaks through, or it hasn't healed after two weeks.
- You notice pus or redness that keeps spreading.""",
    ),
]

